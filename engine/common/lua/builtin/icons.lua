local ALIASES = {
	pistol = "weapons",
	gun = "weapons",
	box = "entities",
	puzzle = "addons",
	script = "scripts",
	gear = "settings",
}

local bitmaps = {}

local function compile(rows)
	local result = {}

	for y = 1, SIZE do
		local row = rows[y] or ""
		local runs = {}
		local start = nil

		for x = 1, SIZE + 1 do
			local on = x <= SIZE and row:sub(x, x) == "#"

			if on and not start then
				start = x
			elseif not on and start then
				runs[#runs + 1] = { start - 1, x - start }
				start = nil
			end
		end

		result[y] = runs
	end

	return result
end

for name, rows in pairs(SOURCE) do
	bitmaps[name] = compile(rows)
end

cc.icon = {}

function cc.icon.Exists(name)
	return bitmaps[ALIASES[name] or name] ~= nil
end

function cc.icon.Draw(name, x, y, size, color)
	local bitmap = bitmaps[ALIASES[name] or name]

	if not bitmap then
		return false
	end

	local unit = math.max(1, math.floor(size / SIZE))
	local offset = math.floor((size - unit * SIZE) / 2)
	local r, g, b, a = color[1], color[2], color[3], color[4] or 255

	for row = 1, SIZE do
		local runs = bitmap[row]

		for i = 1, #runs do
			cc.draw.Rect(math.floor(x + offset + runs[i][1] * unit), math.floor(y + offset + (row - 1) * unit), runs[i][2] * unit, unit, r, g, b, a)
		end
	end

	return true
end
